-- Expedientes internos de alquiler. La renta es visible para el personal autorizado;
-- la liquidación neta al propietario vive en una tabla con RLS exclusivo de owner/admin.

create table if not exists public.rental_dossiers (
  id uuid primary key default gen_random_uuid(),
  property_id uuid not null unique references public.properties(id) on delete restrict,
  tenant_name text not null default '',
  tenant_phone text,
  tenant_email text,
  contract_start date,
  contract_end date,
  current_rent numeric(16,2) not null default 0 check (current_rent >= 0),
  rent_currency text not null default 'ARS' check (rent_currency in ('ARS','USD')),
  increase_index text not null default '',
  increase_interval_months smallint check (increase_interval_months is null or increase_interval_months between 1 and 36),
  next_increase_on date,
  status text not null default 'draft' check (status in ('draft','active','ended','cancelled')),
  notes text not null default '',
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint rental_dossier_contract_dates_check check (contract_end is null or contract_start is null or contract_end >= contract_start),
  constraint rental_dossier_tenant_name_length check (length(tenant_name) <= 180),
  constraint rental_dossier_notes_length check (length(notes) <= 12000)
);
create index if not exists rental_dossiers_status_idx on public.rental_dossiers(status, contract_end);

create table if not exists public.rental_events (
  id uuid primary key default gen_random_uuid(),
  dossier_id uuid not null references public.rental_dossiers(id) on delete restrict,
  event_type text not null check (event_type in ('rent_increase','payment','repair','inspection','notice','document','contract','other')),
  title text not null check (length(trim(title)) between 2 and 180),
  description text not null default '' check (length(description) <= 8000),
  occurred_on date not null default current_date,
  due_on date,
  paid_on date,
  payment_status text check (payment_status is null or payment_status in ('pending','paid','late','partial')),
  amount numeric(16,2) check (amount is null or amount >= 0),
  currency text check (currency is null or currency in ('ARS','USD')),
  previous_rent numeric(16,2) check (previous_rent is null or previous_rent >= 0),
  new_rent numeric(16,2) check (new_rent is null or new_rent >= 0),
  effective_on date,
  index_name text,
  reference text,
  document_path text,
  created_by uuid,
  created_at timestamptz not null default now(),
  constraint rental_event_payment_dates_check check (paid_on is null or due_on is null or paid_on >= due_on or payment_status in ('partial','late','paid'))
);
create index if not exists rental_events_dossier_date_idx on public.rental_events(dossier_id, occurred_on desc, created_at desc);

-- Liquidaciones y netos del dueño nunca se exponen al personal general.
create table if not exists public.rental_owner_settlements (
  id uuid primary key default gen_random_uuid(),
  dossier_id uuid not null references public.rental_dossiers(id) on delete restrict,
  period_start date not null,
  period_end date not null,
  gross_rent numeric(16,2) not null default 0 check (gross_rent >= 0),
  deductions numeric(16,2) not null default 0 check (deductions >= 0),
  net_to_owner numeric(16,2) not null default 0,
  currency text not null default 'ARS' check (currency in ('ARS','USD')),
  status text not null default 'draft' check (status in ('draft','ready','paid')),
  paid_at date,
  notes text not null default '',
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint rental_settlement_period_check check (period_end >= period_start),
  constraint rental_settlement_notes_length check (length(notes) <= 8000)
);
create index if not exists rental_owner_settlements_dossier_idx on public.rental_owner_settlements(dossier_id, period_end desc);

create table if not exists public.rental_activity_audit (
  id bigint generated by default as identity primary key,
  property_id uuid not null,
  actor_id uuid,
  actor_email text,
  action text not null check (action in ('INSERT','UPDATE','DELETE')),
  entity_table text not null check (entity_table in ('rental_dossiers','rental_events','rental_owner_settlements')),
  entity_id text not null,
  old_values jsonb,
  new_values jsonb,
  created_at timestamptz not null default now()
);
create index if not exists rental_activity_audit_property_created_idx on public.rental_activity_audit(property_id, created_at desc);

create or replace function public.rental_touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
