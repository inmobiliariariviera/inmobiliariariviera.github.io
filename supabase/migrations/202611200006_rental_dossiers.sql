create or replace function public.rental_validate_property()
returns trigger language plpgsql set search_path = '' as $$
begin
  if not exists (select 1 from public.properties p where p.id = new.property_id and p.operation = 'Alquiler') then
    raise exception 'El expediente sólo puede asociarse a una propiedad de alquiler';
  end if;
  return new;
end;
$$;
drop trigger if exists rental_dossiers_validate_property on public.rental_dossiers;
create trigger rental_dossiers_validate_property before insert or update of property_id on public.rental_dossiers
for each row execute procedure public.rental_validate_property();

create or replace function public.rental_audit_change()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  v_actor_email text;
  v_property_id uuid;
  v_entity_id text;
  v_old jsonb;
  v_new jsonb;
  v_dossier_id uuid;
begin
  if tg_op <> 'INSERT' then v_old := pg_catalog.to_jsonb(old); end if;
  if tg_op <> 'DELETE' then v_new := pg_catalog.to_jsonb(new); end if;
  select u.email into v_actor_email from auth.users u where u.id = auth.uid();

  if tg_table_name = 'rental_dossiers' then
    v_property_id := case when tg_op = 'DELETE' then old.property_id else new.property_id end;
    v_entity_id := case when tg_op = 'DELETE' then old.id::text else new.id::text end;
  else
    v_dossier_id := case when tg_op = 'DELETE' then old.dossier_id else new.dossier_id end;
    select d.property_id into v_property_id from public.rental_dossiers d where d.id = v_dossier_id;
    v_entity_id := case when tg_op = 'DELETE' then old.id::text else new.id::text end;
  end if;

  if v_property_id is not null then
    insert into public.rental_activity_audit(actor_id, actor_email, action, entity_table, entity_id, property_id, old_values, new_values)
    values (auth.uid(), v_actor_email, tg_op, tg_table_name, v_entity_id, v_property_id, v_old, v_new);
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;
drop trigger if exists rental_dossiers_audit on public.rental_dossiers;
create trigger rental_dossiers_audit after insert or update or delete on public.rental_dossiers
for each row execute procedure public.rental_audit_change();
drop trigger if exists rental_events_audit on public.rental_events;
create trigger rental_events_audit after insert or update or delete on public.rental_events
for each row execute procedure public.rental_audit_change();
drop trigger if exists rental_owner_settlements_audit on public.rental_owner_settlements;
create trigger rental_owner_settlements_audit after insert or update or delete on public.rental_owner_settlements
for each row execute procedure public.rental_audit_change();

-- Los eventos son append-only. Únicamente se permite adjuntar una vez el archivo
-- privado a un evento documental, mediante la función autorizada de abajo.
create or replace function public.rental_event_immutable()
returns trigger language plpgsql set search_path = '' as $$
begin
  if tg_op = 'DELETE' then raise exception 'Los eventos de alquiler son inmutables'; end if;
  if tg_op = 'UPDATE' and not (
    old.document_path is null and new.document_path is not null
    and (pg_catalog.to_jsonb(old) - 'document_path') = (pg_catalog.to_jsonb(new) - 'document_path')
  ) then
    raise exception 'Los eventos de alquiler no se editan; agregá un nuevo evento de corrección';
  end if;
  return new;
end;
$$;
drop trigger if exists rental_events_immutable on public.rental_events;
create trigger rental_events_immutable before update or delete on public.rental_events
for each row execute procedure public.rental_event_immutable();

create or replace function public.record_rental_event(
  p_dossier_id uuid,
  p_event_type text,
  p_title text,
  p_description text default '',
  p_occurred_on date default current_date,
  p_due_on date default null,
  p_paid_on date default null,
  p_payment_status text default null,
  p_amount numeric default null,
  p_currency text default null,
  p_reference text default null
)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_id uuid;
begin
  if not public.is_staff() then raise exception 'No tenés permiso para registrar eventos de alquiler'; end if;
  if p_event_type not in ('payment','repair','inspection','notice','document','contract','other') then
    raise exception 'Tipo de evento no permitido';
  end if;
  if p_title is null or pg_catalog.length(pg_catalog.btrim(p_title)) not between 2 and 180 then raise exception 'El título debe tener entre 2 y 180 caracteres'; end if;
  if p_description is not null and pg_catalog.length(p_description) > 8000 then raise exception 'La descripción excede el tamaño permitido'; end if;
  if p_amount is not null and (p_amount < 0 or coalesce(p_currency, '') not in ('ARS','USD')) then raise exception 'Importe o moneda inválidos'; end if;
  if p_event_type <> 'payment' and p_amount is not null then raise exception 'Sólo los pagos de alquiler admiten un importe visible para el personal'; end if;
  if p_event_type = 'payment' and (p_amount is null or coalesce(p_payment_status, '') not in ('pending','paid','late','partial')) then raise exception 'Indicá importe y estado del pago'; end if;
  if p_payment_status is not null and p_payment_status not in ('pending','paid','late','partial') then raise exception 'Estado de pago inválido'; end if;
  if p_reference is not null and pg_catalog.length(p_reference) > 180 then raise exception 'La referencia es demasiado extensa'; end if;

  insert into public.rental_events(dossier_id, event_type, title, description, occurred_on, due_on, paid_on, payment_status, amount, currency, reference, created_by)
  values (p_dossier_id, p_event_type, pg_catalog.btrim(p_title), coalesce(p_description,''), coalesce(p_occurred_on,current_date), p_due_on, p_paid_on, p_payment_status, p_amount, p_currency, p_reference, auth.uid())
  returning id into v_id;
  return v_id;
end;
$$;

create or replace function public.record_rental_increase(
  p_dossier_id uuid,
  p_effective_on date,
  p_new_rent numeric,
  p_currency text,
  p_index_name text default '',
  p_reference text default null,
  p_description text default ''
)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_dossier public.rental_dossiers%rowtype; v_id uuid;
begin
  if not public.is_admin() then raise exception 'Sólo Dueño o Administrador puede registrar aumentos'; end if;
  if p_new_rent is null or p_new_rent <= 0 or p_currency not in ('ARS','USD') or p_effective_on is null then raise exception 'Importe, moneda y fecha efectiva son obligatorios'; end if;
  select * into v_dossier from public.rental_dossiers where id = p_dossier_id for update;
  if not found then raise exception 'No existe el expediente de alquiler'; end if;
  if p_new_rent <= v_dossier.current_rent then raise exception 'El nuevo canon debe ser mayor al canon vigente; para otra corrección, registrá un evento'; end if;

  insert into public.rental_events(dossier_id, event_type, title, description, occurred_on, amount, currency, previous_rent, new_rent, effective_on, index_name, reference, created_by)
  values (p_dossier_id, 'rent_increase', 'Aumento del canon', coalesce(p_description,''), p_effective_on, p_new_rent, p_currency, v_dossier.current_rent, p_new_rent, p_effective_on, coalesce(p_index_name,''), p_reference, auth.uid())
  returning id into v_id;
  update public.rental_dossiers
  set current_rent = p_new_rent,
      rent_currency = p_currency,
      next_increase_on = case when increase_interval_months is null then next_increase_on else (p_effective_on + (interval '1 month' * increase_interval_months))::date end
  where id = p_dossier_id;
  return v_id;
end;
$$;

create or replace function public.attach_rental_document(p_event_id uuid, p_path text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_property_id uuid; v_event public.rental_events%rowtype;
begin
  if not public.is_staff() then raise exception 'No tenés permiso para adjuntar documentos'; end if;
  select e.* into v_event from public.rental_events e where e.id = p_event_id for update;
  if not found or v_event.event_type <> 'document' or v_event.document_path is not null then raise exception 'El evento no admite un archivo nuevo'; end if;
  select d.property_id into v_property_id from public.rental_dossiers d where d.id = v_event.dossier_id;
  if p_path is null or pg_catalog.length(p_path) > 260 or p_path !~ ('^' || v_property_id::text || '/[A-Za-z0-9._-]{1,220}$') then raise exception 'Ruta del documento inválida'; end if;
  update public.rental_events set document_path = p_path where id = p_event_id;
  return p_event_id;
end;
$$;

